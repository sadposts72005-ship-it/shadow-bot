const handler = async (m, conn, targetSection = null) => {
    try {
        let from = m.key?.remoteJid || m.chat || '';
        if (!from) return;

        let botName = m.botName || conn.botName || 'شادو';
        let isSubBot = false;
        let myNumber = conn.user?.id?.split(':')[0]?.replace(/[^0-9]/g, '') || '';
        if (myNumber) {
            const subConfigPath = path.join(process.cwd(), 'sessions', 'sub_bots', myNumber, 'config.json');
            if (fs.existsSync(subConfigPath)) {
                isSubBot = true;
                try {
                    let cfg = JSON.parse(fs.readFileSync(subConfigPath, 'utf8'));
                    if (cfg.botName) botName = cfg.botName;
                } catch (e) {}
            } else {
                const configPath = path.join(process.cwd(), 'sessions', `session_${myNumber}`, 'bot_config.json');
                if (fs.existsSync(configPath)) {
                    try {
                        let cfg = JSON.parse(fs.readFileSync(configPath, 'utf8'));
                        if (cfg.botName) botName = cfg.botName;
                    } catch (e) {}
                }
            }
        }

        const menuText = getMenuSection(targetSection, botName, isSubBot) || getMenuSection('main', botName, isSubBot);

        // تسجيل هذا الشات كأنه طلب المنيو مؤخراً
        recentMenuChats.set(from, Date.now());

        try {
            await conn.sendMessage(from, { react: { text: '📜', key: m.key } }).catch(() => {});
        } catch (e) {}

        await delay(1000);
        await conn.sendMessage(from, { text: menuText }, { quoted: m }).catch(() => {});
    } catch (err) {
        console.log('خطأ في معالجة المنيو:', err);
    }
};

handler.command = /^(اوامر|أوامر|منيو|المنيو|menu|help)$/i;
export default handler;
