            if (!game) return false;

            if (!game.players.includes(sender)) {
                await triggerEffects();
                await conn.sendMessage(rawId, { text: '⚠️ أنت مش منضم في اللعبة أصلاً يا غالي!' }, { quoted: mek });
                return true;
            }

            let pName = game.names[sender] || getPushName(mek, conn, sender);
            game.players = game.players.filter(p => p !== sender);
            game.askedPlayers = game.askedPlayers.filter(p => p !== sender);

